# COMMENTS IN PYTHON
# Take care this is single comment using the hash symbol --> #
# We can make comments also in other ways using single, double and triple quotes -->' ' or " " or """ """
'this is comment using single quotes'
"this is comment using double quotes"
"""this is 
comment using 
trible quotes"""
# NOTE : when u use triple quotes u can split text in multiple lines single and double can't work without Parenthesis
# Parenthesis can help with using single or double or triple quotes see the difference
('this is comment '
 'using single quotes')
("this is comment "
 "using double quotes")
("""this is 
comment using 
trible quotes""")
# also """ """ equals to ''' '''
'''this is 
comment using 
triple quotes'''
